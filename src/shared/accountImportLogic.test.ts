import test from 'node:test';
import assert from 'node:assert/strict';
import {
  parseAccountImportRows,
  parseScheduledDaysText,
  parseScheduledWeeksText,
  parseShiftTimeRange,
  type AccountImportDefaults,
} from './accountImportLogic';

const BASE_DEFAULTS: AccountImportDefaults = {
  defaultRole: 'petugas',
  defaultDivision: 'Sekbid Kedisiplinan',
  defaultKelas: 'XI-A',
  defaultDays: ['Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'],
  defaultWeeks: [1, 2, 3, 4],
  defaultShiftStart: '06:30',
  defaultShiftEnd: '08:30',
  cycleWeeks: 2,
  allowAdminRole: true,
};

test('parseScheduledDaysText parses ranges, comma lists, and weekdays aliases', () => {
  assert.deepEqual(parseScheduledDaysText('Senin, Rabu, Jumat'), ['Senin', 'Rabu', 'Jumat']);
  assert.deepEqual(parseScheduledDaysText('Senin - Kamis'), [
    'Senin',
    'Selasa',
    'Rabu',
    'Kamis',
  ]);
  assert.deepEqual(parseScheduledDaysText('Senin s.d. Sabtu'), [
    'Senin',
    'Selasa',
    'Rabu',
    'Kamis',
    'Jumat',
    'Sabtu',
  ]);
  assert.equal(parseScheduledDaysText('Semua Hari').length, 7);
});

test('parseScheduledWeeksText and parseShiftTimeRange handle flexible formats', () => {
  assert.deepEqual(parseScheduledWeeksText('Minggu 1 & 2', 2), [1, 2]);
  assert.deepEqual(parseScheduledWeeksText('1, 3', 4), [1, 3]);
  assert.deepEqual(parseShiftTimeRange('06.30 - 08.15'), { start: '06:30', end: '08:15' });
});

test('parseAccountImportRows parses complete Excel sheet with headers and mixed explicit/auto fields', () => {
  const matrix = [
    ['DAFTAR AKUN PETUGAS PIKET OSIS'],
    [],
    [
      'No',
      'Nama Lengkap',
      'Username',
      'Password',
      'Role',
      'Kelas',
      'Divisi',
      'Jadwal Piket',
      'Minggu Piket',
      'Jam Mulai',
      'Jam Selesai',
    ],
    [1, 'Ahmad Fauzi', 'ahmad.fauzi', 'rahasia123', 'Petugas', '11A', 'Sekbid Kedisiplinan', 'Senin, Rabu', '1', '06:30', '08:15'],
    [2, 'Siti Nurhaliza', '', '', 'Admin', '12B', 'Pengurus Inti', 'Senin-Sabtu (06:45-09:00)', 'Semua', '', ''],
  ];

  const result = parseAccountImportRows(matrix, BASE_DEFAULTS);
  assert.equal(result.headerRowNumber, 3);
  assert.equal(result.entries.length, 2);
  assert.equal(result.skipped.length, 0);

  const first = result.entries[0];
  assert.equal(first.name, 'Ahmad Fauzi');
  assert.equal(first.username, 'ahmad.fauzi');
  assert.equal(first.password, 'rahasia123');
  assert.equal(first.usernameAutoGenerated, false);
  assert.equal(first.passwordAutoGenerated, false);
  assert.equal(first.role, 'petugas');
  assert.equal(first.kelas, '11A');
  assert.deepEqual(first.scheduledDays, ['Senin', 'Rabu']);
  assert.deepEqual(first.scheduledWeeks, [1]);
  assert.equal(first.shiftStart, '06:30');
  assert.equal(first.shiftEnd, '08:15');

  const second = result.entries[1];
  assert.equal(second.name, 'Siti Nurhaliza');
  assert.equal(second.username, undefined);
  assert.equal(second.password, undefined);
  assert.equal(second.usernameAutoGenerated, true);
  assert.equal(second.passwordAutoGenerated, true);
  assert.equal(second.role, 'admin');
  assert.deepEqual(second.scheduledDays, ['Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu']);
  assert.equal(second.shiftStart, '06:45');
  assert.equal(second.shiftEnd, '09:00');
});

test('parseAccountImportRows validates duplicate usernames, short passwords, invalid times, and RBAC restrictions', () => {
  const matrix = [
    ['Nama Lengkap', 'Username', 'Password', 'Role', 'Jadwal Piket', 'Jam Mulai', 'Jam Selesai'],
    ['Budi Satu', 'budi.osis', '123', 'Petugas', 'Senin', '06:30', '08:30'], // password < 6
    ['Budi Dua', 'budi.osis', 'aman123', 'Petugas', 'Selasa', '06:30', '08:30'], // valid
    ['Budi Tiga', 'budi.osis', 'aman123', 'Petugas', 'Rabu', '06:30', '08:30'], // duplicate username
    ['Dewi Admin', 'dewi.adm', 'aman123', 'Admin', 'Senin', '06:30', '08:30'], // blocked for admin requester
    ['Dev Rogue', 'dev.rogue', 'aman123', 'Developer', 'Senin', '06:30', '08:30'], // never allowed
    ['Jam Salah', 'jam.salah', 'aman123', 'Petugas', 'Senin', '09:00', '07:00'], // start >= end
  ];

  const result = parseAccountImportRows(matrix, {
    ...BASE_DEFAULTS,
    allowAdminRole: false,
  });

  assert.equal(result.entries.length, 1);
  assert.equal(result.entries[0].name, 'Budi Dua');
  assert.equal(result.duplicateUsernameCount, 1);
  assert.equal(result.skipped.length, 5);
  assert.match(result.skipped[0].reason, /minimal 6 karakter/i);
  assert.match(result.skipped[1].reason, /ganda/i);
  assert.match(result.skipped[2].reason, /Admin hanya diperbolehkan/i);
  assert.match(result.skipped[3].reason, /Developer tidak dapat/i);
  assert.match(result.skipped[4].reason, /lebih awal/i);
});
