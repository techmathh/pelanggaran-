export function normalizeImportedUsername(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/^@+/, '')
    .replace(/[^a-z0-9._-]/g, '')
    .slice(0, 32);
}

export function normalizeTimeToken(raw: string): string | null {
  const cleaned = raw.trim();
  if (!cleaned) return null;

  // Handle Excel decimal day fraction if somehow passed as string (e.g. "0.2708333")
  if (/^0\.\d+$/.test(cleaned)) {
    const frac = Number(cleaned);
    if (Number.isFinite(frac) && frac >= 0 && frac < 1) {
      const totalMins = Math.round(frac * 24 * 60);
      const hh = Math.floor(totalMins / 60) % 24;
      const mm = totalMins % 60;
      return `${String(hh).padStart(2, '0')}:${String(mm).padStart(2, '0')}`;
    }
  }

  const m = cleaned.match(/^(\d{1,2})[:.](\d{2})(?::\d{2})?$/);
  if (!m) return null;
  const h = Number(m[1]);
  const min = Number(m[2]);
  if (h < 0 || h > 23 || min < 0 || min > 59) return null;
  return `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
}

export function parseShiftTimeRange(raw: string): { start?: string; end?: string } {
  const cleaned = raw.trim();
  if (!cleaned) return {};
  const matches = cleaned.match(/\d{1,2}[:.]\d{2}(?::\d{2})?/g);
  if (!matches || matches.length === 0) return {};
  const start = normalizeTimeToken(matches[0]) ?? undefined;
  const end = matches.length >= 2 ? (normalizeTimeToken(matches[1]) ?? undefined) : undefined;
  return { start, end };
}

export function parseScheduledDaysText(raw: string): HariPiket[] {
  const text = raw.trim();
  if (!text) return [];
  const lower = text.toLowerCase();

  if (
    /\bsemua\s*hari\b/.test(lower) ||
    lower === 'semua' ||
    lower === 'setiap hari' ||
    lower === 'all'
  ) {
    return [...HARI_LIST];
  }
  if (/\bhari\s*sekolah\b/.test(lower) || lower === 'weekdays') {
    return [...SEKOLAH_DAYS];
  }

  const chosen = new Set<HariPiket>();

  // Detect ranges like "Senin - Sabtu" or "Senin s.d. Jumat" or "Senin s/d Jumat"
  const rangeRegex =
    /\b(minggu|ahad|senin|selasa|rabu|kamis|jumat|jum'at|sabtu)\b\s*(?:-|–|—|s\.?d\.?|s\/d|sampai|hingga|to)\s*\b(minggu|ahad|senin|selasa|rabu|kamis|jumat|jum'at|sabtu)\b/gi;
  let match: RegExpExecArray | null;
  while ((match = rangeRegex.exec(lower)) !== null) {
    const startIdx = DAY_INDEX_MAP[match[1]];
    const endIdx = DAY_INDEX_MAP[match[2]];
    if (startIdx !== undefined && endIdx !== undefined) {
      let cur = startIdx;
      for (let guard = 0; guard < 7; guard++) {
        chosen.add(HARI_LIST[cur]);
        if (cur === endIdx) break;
        cur = (cur + 1) % 7;
      }
    }
  }

  // Detect individual day names mentioned anywhere in the string
  const tokens = lower.split(/[^a-z']+/).filter(Boolean);
  for (const tok of tokens) {
    const idx = DAY_INDEX_MAP[tok];
    if (idx !== undefined) {
      chosen.add(HARI_LIST[idx]);
    }
  }

  return HARI_LIST.filter((d) => chosen.has(d));
}

export function parseScheduledWeeksText(raw: string, cycleWeeks: number): number[] {
  const safeCycle = clampCycleWeeks(cycleWeeks);
  const text = raw.trim().toLowerCase();
  if (!text) return [];
  if (
    text.includes('semua') ||
    text.includes('setiap minggu') ||
    text === 'all'
  ) {
    return [...ALL_ROTATION_WEEKS];
  }

  const weeks = new Set<number>();
  const rangeMatch = text.match(/\b([1-4])\s*(?:-|–|s\.?d\.?|s\/d|sampai)\s*([1-4])\b/);
  if (rangeMatch) {
    const a = Number(rangeMatch[1]);
    const b = Number(rangeMatch[2]);
    const lo = Math.min(a, b);
    const hi = Math.max(a, b);
    for (let w = lo; w <= hi; w++) {
      if (w >= 1 && w <= safeCycle) weeks.add(w);
    }
  }

  const numMatches = text.match(/\b[1-4]\b/g);
  if (numMatches) {
    for (const nStr of numMatches) {
      const n = Number(nStr);
      if (n >= 1 && n <= 4) {
        weeks.add(n);
      }
    }
  }

  return Array.from(weeks).sort((a, b) => a - b);
}

function isMetadataOrExampleNoteRow(cells: string[]): boolean {
  const nonEmpty = cells.filter(Boolean);
  if (nonEmpty.length === 0) return true;
  if (nonEmpty.length === 1) {
    const lower = nonEmpty[0].toLowerCase();
    if (
      lower.includes('sma negeri') ||
      lower.includes('template') ||
      lower.includes('daftar akun') ||
      lower.includes('petunjuk')
    ) {
      return true;
    }
  }
  return false;
}

/**
 * Parses an uploaded Excel/CSV 2D matrix into validated account creation entries.
 * Supports flexible Indonesian/English column names including combined "Jadwal Piket"
 * cells (e.g. "Senin, Rabu (06:30-08:30) | Minggu 1, 2").
 */
export function parseAccountImportRows(
  rawRows: unknown[][],
  defaults: AccountImportDefaults
): ParsedAccountImportResult {
  const skipped: ParsedAccountImportSkip[] = [];
  const emptyCols = {
    nameCol: 0,
    usernameCol: 1,
    passwordCol: 2,
    roleCol: -1,
    kelasCol: -1,
    divisionCol: -1,
    scheduleCol: 3,
    weeksCol: -1,
    shiftCol: -1,
    shiftStartCol: -1,
    shiftEndCol: -1,
  };

  if (!Array.isArray(rawRows) || rawRows.length === 0) {
    return {
      entries: [],
      skipped: [],
      headerRowNumber: null,
      duplicateUsernameCount: 0,
      detectedColumns: emptyCols,
    };
  }

  // Locate header row in top 15 rows
  let headerRowIndex = -1;
  let nameCol = -1;
  let usernameCol = -1;
  let passwordCol = -1;
  let roleCol = -1;
  let kelasCol = -1;
  let divisionCol = -1;
  let scheduleCol = -1;
  let weeksCol = -1;
  let shiftCol = -1;
  let shiftStartCol = -1;
  let shiftEndCol = -1;

  const scanLimit = Math.min(rawRows.length, 15);
  for (let r = 0; r < scanLimit; r++) {
    const row = Array.isArray(rawRows[r]) ? rawRows[r] : [];
    const tokens = row.map((c) => normalizeHeaderToken(cleanCell(c)));
    const foundName = tokens.findIndex((t) => isNameHeader(t));
    if (foundName === -1) continue;

    const foundUser = tokens.findIndex((t) => isUsernameHeader(t));
    const foundPass = tokens.findIndex((t) => isPasswordHeader(t));
    const foundRole = tokens.findIndex((t) => isRoleHeader(t));
    const foundKelas = tokens.findIndex((t) => isKelasHeader(t));
    const foundDiv = tokens.findIndex((t) => isDivisionHeader(t));
    const foundSched = tokens.findIndex((t) => isScheduleHeader(t));
    const foundWeeks = tokens.findIndex((t) => isWeeksHeader(t));
    const foundShift = tokens.findIndex((t) => isShiftHeader(t));
    const foundStart = tokens.findIndex((t) => isShiftStartHeader(t));
    const foundEnd = tokens.findIndex((t) => isShiftEndHeader(t));

    // Must match at least name + one other account column to be confident it's the header
    if (
      foundUser >= 0 ||
      foundPass >= 0 ||
      foundSched >= 0 ||
      foundRole >= 0 ||
      foundKelas >= 0
    ) {
      headerRowIndex = r;
      nameCol = foundName;
      usernameCol = foundUser;
      passwordCol = foundPass;
      roleCol = foundRole;
      kelasCol = foundKelas;
      divisionCol = foundDiv;
      scheduleCol = foundSched;
      weeksCol = foundWeeks;
      shiftCol = foundShift;
      shiftStartCol = foundStart;
      shiftEndCol = foundEnd;
      break;
    }
  }

  // Headerless fallback: infer [No?, Nama, Username, Password, Jadwal Piket]
  if (headerRowIndex === -1) {
    const sampleRow = rawRows.find(
      (r) => Array.isArray(r) && r.some((c) => cleanCell(c).length > 0)
    );
    const cells = (sampleRow ?? []).map(cleanCell);
    const startsWithNo = cells.length >= 3 && /^\d{1,3}$/.test(cells[0]);
    const offset = startsWithNo ? 1 : 0;
    nameCol = offset;
    usernameCol = cells.length > offset + 1 ? offset + 1 : -1;
    passwordCol = cells.length > offset + 2 ? offset + 2 : -1;
    scheduleCol = cells.length > offset + 3 ? offset + 3 : -1;
  }

  const entries: ParsedAccountImportRow[] = [];
  const seenExplicitUsernames = new Set<string>();
  let duplicateUsernameCount = 0;
  const safeCycle = clampCycleWeeks(defaults.cycleWeeks);
  const startRow = headerRowIndex >= 0 ? headerRowIndex + 1 : 0;

  for (let r = startRow; r < rawRows.length; r++) {
    const rawRow = Array.isArray(rawRows[r]) ? rawRows[r] : [];
    const cells = rawRow.map(cleanCell);
    if (isMetadataOrExampleNoteRow(cells)) continue;

    const rawName = nameCol >= 0 ? (cells[nameCol] ?? '') : '';
    const rawUser = usernameCol >= 0 ? (cells[usernameCol] ?? '') : '';
    const rawPass = passwordCol >= 0 ? (cells[passwordCol] ?? '') : '';
    const rawRole = roleCol >= 0 ? (cells[roleCol] ?? '') : '';
    const rawKelas = kelasCol >= 0 ? (cells[kelasCol] ?? '') : '';
    const rawDiv = divisionCol >= 0 ? (cells[divisionCol] ?? '') : '';
    const rawSched = scheduleCol >= 0 ? (cells[scheduleCol] ?? '') : '';
    const rawWeeks = weeksCol >= 0 ? (cells[weeksCol] ?? '') : '';
    const rawShift = shiftCol >= 0 ? (cells[shiftCol] ?? '') : '';
    const rawShiftStart = shiftStartCol >= 0 ? (cells[shiftStartCol] ?? '') : '';
    const rawShiftEnd = shiftEndCol >= 0 ? (cells[shiftEndCol] ?? '') : '';

    // Skip repeated header lines
    if (isNameHeader(normalizeHeaderToken(rawName))) {
      continue;
    }

    const rowNumber = r + 1;
    if (!rawName) {
      // Skip rows that only have a serial number in col 0
      const hasOtherData = Boolean(rawUser || rawPass || rawSched || rawKelas);
      if (hasOtherData) {
        skipped.push({ rowNumber, reason: 'Nama lengkap kosong' });
      }
      continue;
    }

    // Parse Role
    let resolvedRole: 'admin' | 'petugas' = defaults.defaultRole;
    if (rawRole) {
      const roleLower = rawRole.toLowerCase();
      if (roleLower.includes('dev')) {
        skipped.push({
          rowNumber,
          name: rawName,
          reason: 'Role Developer tidak dapat dibuat melalui import Excel.',
        });
        continue;
      } else if (roleLower.includes('admin')) {
        if (!defaults.allowAdminRole) {
          skipped.push({
            rowNumber,
            name: rawName,
            reason: 'Admin hanya diperbolehkan mengimpor akun Petugas Piket.',
          });
          continue;
        }
        resolvedRole = 'admin';
      } else if (roleLower.includes('petugas') || roleLower.includes('piket') || roleLower.includes('osis')) {
        resolvedRole = 'petugas';
      } else {
        skipped.push({
          rowNumber,
          name: rawName,
          reason: `Role "${rawRole}" tidak dikenali (gunakan Petugas atau Admin).`,
        });
        continue;
      }
    }

    // Parse Username format first (reserve in seenExplicitUsernames only after all row validations pass)
    let explicitUsername: string | undefined;
    if (rawUser) {
      const normalizedUser = normalizeImportedUsername(rawUser);
      if (normalizedUser.length < 3) {
        skipped.push({
          rowNumber,
          name: rawName,
          reason: `Username "${rawUser}" terlalu pendek (minimal 3 karakter huruf/angka).`,
        });
        continue;
      }
      if (seenExplicitUsernames.has(normalizedUser)) {
        duplicateUsernameCount++;
        skipped.push({
          rowNumber,
          name: rawName,
          reason: `Username "${normalizedUser}" ganda di dalam file Excel.`,
        });
        continue;
      }
      explicitUsername = normalizedUser;
    }

    // Parse Password
    let explicitPassword: string | undefined;
    if (rawPass) {
      if (rawPass.length < 6) {
        skipped.push({
          rowNumber,
          name: rawName,
          reason: `Password untuk "${rawName}" terlalu pendek (minimal 6 karakter).`,
        });
        continue;
      }
      explicitPassword = rawPass;
    }

    // Parse Jadwal Piket (supports days + inline time + inline weeks if combined in one column)
    const parsedDays = rawSched ? parseScheduledDaysText(rawSched) : [];
    const scheduledDays =
      parsedDays.length > 0
        ? parsedDays
        : defaults.defaultDays.length > 0
          ? [...defaults.defaultDays]
          : [...SEKOLAH_DAYS];

    let parsedWeeks = rawWeeks ? parseScheduledWeeksText(rawWeeks, safeCycle) : [];
    if (parsedWeeks.length === 0 && rawSched && /minggu\s*[1-4]/i.test(rawSched)) {
      parsedWeeks = parseScheduledWeeksText(rawSched, safeCycle);
    }
    const scheduledWeeks =
      resolvedRole === 'admin' || safeCycle === 1
        ? [...ALL_ROTATION_WEEKS]
        : parsedWeeks.length > 0
          ? parsedWeeks
          : defaults.defaultWeeks.length > 0
            ? [...defaults.defaultWeeks]
            : [...ALL_ROTATION_WEEKS];

    // Parse Shift times
    const rangeFromShiftCol = rawShift ? parseShiftTimeRange(rawShift) : {};
    const rangeFromSchedCol = rawSched ? parseShiftTimeRange(rawSched) : {};
    const parsedStart =
      (rawShiftStart ? normalizeTimeToken(rawShiftStart) : null) ??
      rangeFromShiftCol.start ??
      rangeFromSchedCol.start ??
      defaults.defaultShiftStart;
    const parsedEnd =
      (rawShiftEnd ? normalizeTimeToken(rawShiftEnd) : null) ??
      rangeFromShiftCol.end ??
      rangeFromSchedCol.end ??
      defaults.defaultShiftEnd;

    if (parseMinutes(parsedStart) < 0 || parseMinutes(parsedEnd) < 0) {
      skipped.push({
        rowNumber,
        name: rawName,
        reason: 'Format jam piket tidak valid (gunakan HH:MM, misal 06:30).',
      });
      continue;
    }
    if (parseMinutes(parsedStart) >= parseMinutes(parsedEnd)) {
      skipped.push({
        rowNumber,
        name: rawName,
        reason: `Jam mulai (${parsedStart}) harus lebih awal dari jam selesai (${parsedEnd}).`,
      });
      continue;
    }

    const resolvedKelas = rawKelas
      ? rawKelas.toUpperCase().replace(/^KELAS\s+/i, '')
      : defaults.defaultKelas || (resolvedRole === 'admin' ? 'OSIS-ADMIN' : 'XI-A');

    const resolvedDivision =
      rawDiv ||
      defaults.defaultDivision ||
      (resolvedRole === 'admin' ? 'Admin Pengurus OSIS' : 'Sekbid Kedisiplinan');

    if (explicitUsername) {
      seenExplicitUsernames.add(explicitUsername);
    }

    entries.push({
      rowNumber,
      name: rawName,
      username: explicitUsername,
      password: explicitPassword,
      role: resolvedRole,
      division: resolvedDivision,
      kelas: resolvedKelas,
      scheduledDays,
      scheduledWeeks,
      shiftStart: parsedStart,
      shiftEnd: parsedEnd,
      usernameAutoGenerated: !explicitUsername,
      passwordAutoGenerated: !explicitPassword,
    });
  }

  return {
    entries,
    skipped,
    headerRowNumber: headerRowIndex >= 0 ? headerRowIndex + 1 : null,
    duplicateUsernameCount,
    detectedColumns: {
      nameCol,
      usernameCol,
      passwordCol,
      roleCol,
      kelasCol,
      divisionCol,
      scheduleCol,
      weeksCol,
      shiftCol,
      shiftStartCol,
      shiftEndCol,
    },
  };
}
