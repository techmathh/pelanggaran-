import {
  ALL_ROTATION_WEEKS,
  HARI_LIST,
  clampCycleWeeks,
  parseMinutes,
} from './piketLogic';
import type { AccountImportEntry, HariPiket } from './types';

export interface AccountImportDefaults {
  defaultRole: 'admin' | 'petugas';
  defaultDivision: string;
  defaultKelas: string;
  defaultDays: HariPiket[];
  defaultWeeks: number[];
  defaultShiftStart: string;
  defaultShiftEnd: string;
  cycleWeeks: number;
  allowAdminRole: boolean;
}

export interface ParsedAccountImportRow extends AccountImportEntry {
  rowNumber: number;
  role: 'admin' | 'petugas';
  division: string;
  kelas: string;
  scheduledDays: HariPiket[];
  scheduledWeeks: number[];
  shiftStart: string;
  shiftEnd: string;
  usernameAutoGenerated: boolean;
  passwordAutoGenerated: boolean;
}

export interface ParsedAccountImportSkip {
  rowNumber: number;
  name?: string;
  reason: string;
}

export interface ParsedAccountImportResult {
  entries: ParsedAccountImportRow[];
  skipped: ParsedAccountImportSkip[];
  headerRowNumber: number | null;
  duplicateUsernameCount: number;
  detectedColumns: {
    nameCol: number;
    usernameCol: number;
    passwordCol: number;
    roleCol: number;
    kelasCol: number;
    divisionCol: number;
    scheduleCol: number;
    weeksCol: number;
    shiftCol: number;
    shiftStartCol: number;
    shiftEndCol: number;
  };
}

const SEKOLAH_DAYS: HariPiket[] = ['Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];

const DAY_INDEX_MAP: Record<string, number> = {
  minggu: 0,
  ahad: 0,
  sunday: 0,
  sun: 0,
  senin: 1,
  senn: 1,
  monday: 1,
  mon: 1,
  selasa: 2,
  tuesday: 2,
  tue: 2,
  rabu: 3,
  wednesday: 3,
  wed: 3,
  kamis: 4,
  thursday: 4,
  thu: 4,
  jumat: 5,
  "jum'at": 5,
  friday: 5,
  fri: 5,
  sabtu: 6,
  saturday: 6,
  sat: 6,
};

function cleanCell(value: unknown): string {
  if (value === null || value === undefined) return '';
  return String(value).replace(/\s+/g, ' ').trim();
}

function normalizeHeaderToken(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

